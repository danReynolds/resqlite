// ignore_for_file: avoid_print
import 'dart:convert';
import 'dart:io';

/// Assembles `docs/experiments/knowledge-graph.json` — the one aggregate a
/// viewer page or an agent needs to answer "what do we currently believe,
/// and on what evidence" without reading two hundred writeups.
///
/// Sources (all per-experiment fragments; nothing here is hand-aggregated):
///
///   experiments/index/NNN.json           — title/status/file, plus ADR-style
///                                           `supersededBy` / `amendedBy`
///                                           experiment lineage
///   experiments/signals/entries/NNN.json  — `directions` and typed `claims`
///   experiments/signals/base.json         — the direction list
///
/// Claim state is derived from edges (`supersedes` / `refutes` inbound ⇒
/// superseded / refuted, else live) — the same derivation
/// `generate_signals.dart` uses for each direction's `beliefs` block.
///
/// Like every `docs/` aggregate this file is owned by the post-merge
/// "Update Docs Data" bot; branches never commit it.
Map<String, Object?> buildKnowledgeGraph({required Directory experimentsDir}) {
  final base = json.decode(
    File('${experimentsDir.path}/signals/base.json').readAsStringSync(),
  ) as Map<String, Object?>;
  final directionIds = [
    for (final d in (base['directions'] as List? ?? const []))
      if (d is Map && d['id'] is String) d['id'] as String,
  ];

  // Per-experiment rows from index fragments (split experiments: first row
  // carries the canonical title/file; statuses are joined).
  // The writeup's **Date:** header supplies the timeline axis for viewers.
  final dateRe = RegExp(r'\*\*Date:\*\*\s*(\d{4}-\d{2}(?:-\d{2})?)');
  final experiments = <String, Map<String, Object?>>{};
  final indexDir = Directory('${experimentsDir.path}/index');
  for (final file in indexDir.listSync().whereType<File>()) {
    if (!file.path.endsWith('.json')) continue;
    final id = file.uri.pathSegments.last.replaceFirst(RegExp(r'\.json$'), '');
    final decoded = json.decode(file.readAsStringSync());
    final rows = (decoded is List ? decoded : [decoded]).cast<Map>();
    if (rows.isEmpty) continue;
    final first = rows.first;
    final writeup = File(
      '${experimentsDir.path}/${first['file'] ?? '$id.md'}',
    );
    final date = writeup.existsSync()
        ? dateRe.firstMatch(writeup.readAsStringSync())?.group(1)
        : null;
    experiments[id] = {
      'id': id,
      'title': first['title'],
      'file': first['file'] ?? '$id.md',
      if (date != null) 'date': date,
      'status': rows.length == 1
          ? first['status']
          : rows.map((r) => r['status']).join('+'),
      if (first['supersededBy'] != null) 'supersededBy': first['supersededBy'],
      if (first['amendedBy'] != null) 'amendedBy': first['amendedBy'],
    };
  }

  // Claims + entry directions.
  final claims = <Map<String, Object?>>[];
  final supersededBy = <String, List<String>>{};
  final refutedBy = <String, List<String>>{};
  final entriesDir = Directory('${experimentsDir.path}/signals/entries');
  final entryFiles =
      entriesDir.listSync().whereType<File>().where(
        (f) => f.path.endsWith('.json'),
      ).toList()..sort((a, b) => a.path.compareTo(b.path));
  for (final file in entryFiles) {
    final id = file.uri.pathSegments.last.replaceFirst(RegExp(r'\.json$'), '');
    final note = json.decode(file.readAsStringSync()) as Map<String, Object?>;
    final dirs = [
      for (final d in (note['directions'] as List? ?? const [])) d.toString(),
    ];
    experiments[id]?['directions'] = dirs;
    experiments[id]?['outcomeClass'] = note['outcomeClass'];
    for (final c in (note['claims'] as List? ?? const [])) {
      if (c is! Map<String, Object?> || c['id'] is! String) continue;
      claims.add({
        'id': c['id'],
        'source': id,
        'directions': dirs,
        'text': c['text'],
        if (c['conditions'] != null) 'conditions': c['conditions'],
        if (c['edges'] != null) 'edges': c['edges'],
      });
      for (final edge in (c['edges'] as List? ?? const [])) {
        if (edge is! Map || edge['target'] is! String) continue;
        final target = edge['target'] as String;
        if (edge['type'] == 'supersedes') {
          (supersededBy[target] ??= []).add(c['id'] as String);
        } else if (edge['type'] == 'refutes') {
          (refutedBy[target] ??= []).add(c['id'] as String);
        }
      }
    }
  }
  for (final c in claims) {
    final id = c['id'] as String;
    if (refutedBy.containsKey(id)) {
      c['state'] = 'refuted';
      c['by'] = refutedBy[id];
    } else if (supersededBy.containsKey(id)) {
      c['state'] = 'superseded';
      c['by'] = supersededBy[id];
    } else {
      c['state'] = 'live';
    }
  }

  final expIds = experiments.keys.toList()..sort(_compareIds);
  final entriesWithClaims = claims.map((c) => c['source']).toSet().length;
  return {
    '_note':
        'Generated by benchmark/generate_knowledge_graph.dart from the '
        'per-experiment fragments (index/NNN.json + signals/entries/NNN.json). '
        'Bot-owned; do not hand-edit or commit on a branch.',
    'directions': directionIds,
    // Claims are being adopted incrementally: entries without claims still
    // hold their knowledge as changedBeliefs prose and direction currentRead.
    'coverage': {
      'entriesWithClaims': entriesWithClaims,
      'totalEntries': entryFiles.length,
    },
    'experiments': [for (final id in expIds) experiments[id]],
    'claims': claims,
  };
}

int _compareIds(String a, String b) {
  final ma = RegExp(r'^(\d+)(.*)$').firstMatch(a);
  final mb = RegExp(r'^(\d+)(.*)$').firstMatch(b);
  final na = ma == null ? (1 << 30) : int.parse(ma.group(1)!);
  final nb = mb == null ? (1 << 30) : int.parse(mb.group(1)!);
  if (na != nb) return na.compareTo(nb);
  return (ma?.group(2) ?? a).compareTo(mb?.group(2) ?? b);
}

Future<void> main() async {
  final graph = buildKnowledgeGraph(experimentsDir: Directory('experiments'));
  final out = File('docs/experiments/knowledge-graph.json');
  out.createSync(recursive: true);
  out.writeAsStringSync(
    const JsonEncoder.withIndent('  ').convert(graph) + '\n',
  );
  print('Wrote ${out.path}');
}
